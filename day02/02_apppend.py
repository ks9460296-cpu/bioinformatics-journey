# append : add an item to the end of a list 
codons = [] #empty list to hold codons
print(codons) #print the empty list

#list empty so it will print nothing or []

codons.append("ATG") #add the first codon to the list
print(codons) #print the list with one codon

codons.append("CGT") #add the second codon to the list
print(codons) #print the list with two codons

codons.append("GCA") #add the third codon to the list
print(codons) #print the list with three codons

